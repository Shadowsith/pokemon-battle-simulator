// Fetches the German name of every Gen 1-6 species (national dex 1-721) from
// PokeAPI and writes:
//   scripts/species-names.de.json           { "<num>": "<german name>" }  (cache)
//   src/app/core/models/species-names.de.ts  runtime lookup used by the app
//
// Cached, so re-runs only fetch what is missing.
// Run with: node scripts/fetch-species-names.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

const LAST_DEX = 721;
const CACHE_FILE = path.resolve('scripts/species-names.de.json');
const TS_FILE = path.resolve('src/app/core/models/species-names.de.ts');
const CONCURRENCY = 10;
const RETRIES = 3;

async function loadCache() {
  if (!existsSync(CACHE_FILE)) return {};
  try {
    return JSON.parse(await readFile(CACHE_FILE, 'utf8'));
  } catch {
    return {};
  }
}

async function fetchName(num) {
  const url = `https://pokeapi.co/api/v2/pokemon-species/${num}/`;
  for (let attempt = 1; attempt <= RETRIES; attempt++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const json = await res.json();
      return json.names.find((n) => n.language.name === 'de')?.name ?? null;
    } catch (err) {
      if (attempt === RETRIES) throw err;
      await new Promise((r) => setTimeout(r, 300 * attempt));
    }
  }
}

async function runPool(items, worker) {
  let cursor = 0;
  const next = async () => {
    while (cursor < items.length) await worker(items[cursor++]);
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, next));
}

async function main() {
  const cache = await loadCache();
  const nums = Array.from({ length: LAST_DEX }, (_, i) => i + 1);
  const missing = nums.filter((n) => !cache[n]);

  if (missing.length) {
    console.log(`Fetching ${missing.length} German species names from PokeAPI…`);
    let done = 0;
    await runPool(missing, async (num) => {
      try {
        const name = await fetchName(num);
        if (name) cache[num] = name;
        else console.warn(`#${num}: no German name`);
      } catch (err) {
        console.warn(`#${num}: ${err.message}`);
      }
      if (++done % 100 === 0) console.log(`  ${done}/${missing.length}`);
    });
  }

  const ordered = Object.fromEntries(
    nums.filter((n) => cache[n]).map((n) => [n, cache[n]])
  );
  await writeFile(CACHE_FILE, JSON.stringify(ordered, null, 0) + '\n');

  const entries = Object.entries(ordered)
    .map(([num, name]) => `  ${num}: ${JSON.stringify(name)}`)
    .join(',\n');
  const ts = `// AUTO-GENERATED by scripts/fetch-species-names.mjs - do not edit by hand.
// German species names for national dex 1-721 (PokeAPI).

export const SPECIES_NAMES_DE: Record<number, string> = {
${entries}
};

/** German name for a national dex number, falling back to \`fallback\` then "#<num>". */
export function germanSpeciesName(num: number, fallback?: string): string {
  return SPECIES_NAMES_DE[num] ?? fallback ?? \`#\${num}\`;
}
`;
  await writeFile(TS_FILE, ts);

  console.log(
    `Done. ${Object.keys(ordered).length}/${LAST_DEX} names -> ${path.relative(process.cwd(), CACHE_FILE)} + ${path.relative(process.cwd(), TS_FILE)}`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
